import Foundation

func runLayoutTests() {
    let a = tempDir(); make(a, ["__MACOSX/", ".DS_Store", "Fix/", "Fix/Fix v2/", "Fix/Fix v2/dinput8.dll"])
    let plain = tempDir(); make(plain, ["game.exe", "base/"])
    let plainGame = GameFolders(exeFolder: plain, root: plain, is64bit: true)
    check(ModLayout.contentRoot(a, game: plainGame).lastPathComponent == "Fix v2", "contentRoot strips wrappers and junk")

    let m = tempDir(); make(m, ["dinput8.dll", "Widescreen.asi", "Widescreen.ini", "scripts/", "scripts/extra.asi", "readme.txt"])
    let g = GameFolders(exeFolder: URL(fileURLWithPath: "/g/Binaries/Win64"), root: URL(fileURLWithPath: "/g"), is64bit: true)
    let p = ModLayout.dropInPlan(m, game: g)
    check(p?.recipe == .dropIn, "drop-in recognised")
    check(p?.overrides == ["dinput8=n,b"], "override for proxy DLL only")
    check(p?.copies.contains(ModCopy(from: m.appendingPathComponent("scripts/extra.asi"), to: URL(fileURLWithPath: "/g/Binaries/Win64/scripts/extra.asi"))) == true, "subfolders kept, next to exe")
    check(p?.copies.count == 5, "every file copied (folders are not copies)")

    let d = tempDir(); make(d, ["textures/", "textures/wall.tga"])
    check(ModLayout.dropInPlan(d, game: g) == nil, "data mod is not drop-in")

    check(ModLayout.gameRoot(exeFolder: URL(fileURLWithPath: "/G/Binaries/Win64")).path == "/G", "root above Binaries/Win64")
    check(ModLayout.gameRoot(exeFolder: URL(fileURLWithPath: "/G/Sub")).path == "/G/Sub", "ordinary folder is its own root")
    let game = tempDir(); make(game, ["Binaries/", "Binaries/Win64/", "Binaries/Win64/game.exe", "base/", "base/pak000.pk4", "base/pak001.pk4"])
    let gf = GameFolders(exeFolder: game.appendingPathComponent("Binaries/Win64"), root: game, is64bit: true)
    let mm = tempDir(); make(mm, ["base/", "base/maps/", "base/maps/new.map"])
    check(ModLayout.plan(mm, game: gf)?.copies.first?.to == game.appendingPathComponent("base/maps/new.map"), "mirror at game root")
    check(ModLayout.plan(mm, game: gf)?.recipe == .mirror, "mirror recipe")
    let em = tempDir(); make(em, ["Win64/", "Win64/x.cfg"])
    let eg = GameFolders(exeFolder: game.appendingPathComponent("Binaries"), root: game, is64bit: true)
    check(ModLayout.plan(em, game: eg)?.copies.first?.to == game.appendingPathComponent("Binaries/Win64/x.cfg"), "mirror at exe folder")
    let dm = tempDir(); make(dm, ["zzz_hd.pk4", "readme.txt"])
    let dp = ModLayout.plan(dm, game: gf)
    check(dp?.recipe == .dataFiles && dp?.copies == [ModCopy(from: dm.appendingPathComponent("zzz_hd.pk4"), to: game.appendingPathComponent("base/zzz_hd.pk4"))], "pk4 goes to base, readme skipped")
    let pm = tempDir(); make(pm, ["dhewm3.exe", "base.dll", "SDL2.dll"])
    let pp = ModLayout.plan(pm, game: gf)
    check(pp?.recipe == .program && pp?.programExe == game.appendingPathComponent("dhewm3.exe"), "port with no clashing files goes into the game folder")
    check(pp?.copies.allSatisfy { $0.to.deletingLastPathComponent() == game } == true, "every port file goes into the game folder")
    check(pp.flatMap(ModLayout.programName) == "dhewm3", "program named after its exe")
    let g3 = tempDir(); make(g3, ["Doom3.exe", "gamex86.dll", "SDL2.dll", "base/", "base/pak000.pk4"])
    let gf3 = GameFolders(exeFolder: g3, root: g3, is64bit: false)
    let pp3 = ModLayout.plan(pm, game: gf3)
    check(pp3?.recipe == .program, "exe/dll mod is a program, not data files")
    check(pp3?.programExe == g3.deletingLastPathComponent().appendingPathComponent(g3.lastPathComponent + " (dhewm3)/dhewm3.exe"), "port whose files clash gets its own folder")
    let nm = tempDir(); make(nm, ["notes/", "notes/a.xyz"])
    check(ModLayout.plan(nm, game: gf) == nil, "unknown layout -> nil")
    let lone = tempDir(); make(lone, ["ModSetup.exe"])
    check(ModLayout.plan(lone, game: gf) == nil, "installer is not a program")
    let vm = tempDir(); make(vm, ["x86/", "x86/d3d9.dll", "x64/", "x64/d3d9.dll", "readme.txt"])
    check(ModLayout.pickVariant(vm, is64bit: true) == .one(vm.appendingPathComponent("x64")), "x64 chosen for 64-bit game")
    check(ModLayout.pickVariant(vm, is64bit: false) == .one(vm.appendingPathComponent("x86")), "x86 chosen for 32-bit game")
    let om = tempDir(); make(om, ["Option A/", "Option A/a.asi", "Option B/", "Option B/b.asi"])
    if case .ask(let list) = ModLayout.pickVariant(om, is64bit: true) { check(list.count == 2, "ambiguous asks") } else { check(false, "ambiguous asks") }
    let one = tempDir(); make(one, ["only/", "only/a.asi"])
    check(ModLayout.pickVariant(one, is64bit: true) == ModLayout.VariantPick.none, "one folder is not a variant choice")
    let loose = tempDir(); make(loose, ["x64/", "x64/a.dll", "x86/", "x86/a.dll", "mod.ini"])
    check(ModLayout.pickVariant(loose, is64bit: true) == ModLayout.VariantPick.none, "loose file means no variants")
    let pe = tempDir(); make(pe, ["A/", "B/"])
    func writePE(_ u: URL, machine: UInt16) {
        var d = Data(count: 0x100); d[0] = 0x4D; d[1] = 0x5A; d[0x3c] = 0x80
        d[0x80] = 0x50; d[0x81] = 0x45; d[0x84] = UInt8(machine & 0xff); d[0x85] = UInt8(machine >> 8)
        try? d.write(to: u)
    }
    writePE(pe.appendingPathComponent("A/x.dll"), machine: 0x8664); writePE(pe.appendingPathComponent("B/x.dll"), machine: 0x14c)
    check(ModLayout.isPE64(pe.appendingPathComponent("A/x.dll")) == true && ModLayout.isPE64(pe.appendingPathComponent("B/x.dll")) == false, "PE machine read")
    check(ModLayout.isPE64(pe.appendingPathComponent("A")) == nil, "non-PE is nil")
    check(ModLayout.pickVariant(pe, is64bit: true) == ModLayout.VariantPick.none, "PE header alone does not make folders variants")
    let tx = tempDir(); make(tx, ["textures/", "textures/a.tga", "scripts/", "scripts/b.lua"])
    check(ModLayout.pickVariant(tx, is64bit: true) == ModLayout.VariantPick.none, "textures + scripts are not variants")
    let bm = tempDir(); make(bm, ["base/", "base/a.pk4", "mods/", "mods/b.pk4"])
    check(ModLayout.pickVariant(bm, is64bit: true) == ModLayout.VariantPick.none, "base + mods are not variants")
    let inst = tempDir(); make(inst, ["ModSetup.exe", "plain.exe", "Mod.msi", "packed.exe"])
    try? Data("xxxx Inno Setup xxxx".utf8).write(to: inst.appendingPathComponent("packed.exe"))
    check(ModLayout.looksLikeInstaller(inst.appendingPathComponent("ModSetup.exe")), "setup name is installer")
    check(ModLayout.looksLikeInstaller(inst.appendingPathComponent("Mod.msi")), "msi is installer")
    check(ModLayout.looksLikeInstaller(inst.appendingPathComponent("packed.exe")), "Inno Setup marker is installer")
    make(inst, ["Setup.msix", "install.bat"])
    check(ModLayout.looksLikeInstaller(inst.appendingPathComponent("Setup.msix")), "Setup.msix is installer")
    check(ModLayout.looksLikeInstaller(inst.appendingPathComponent("install.bat")), "install.bat is installer")
    check(!ModLayout.looksLikeInstaller(inst.appendingPathComponent("plain.exe")), "plain exe is not installer")

    let g4 = tempDir(); make(g4, ["game.exe", "gamex86.dll", "base/", "base/pak000.pk4"])
    let gf4 = GameFolders(exeFolder: g4, root: g4, is64bit: false)
    let pd = tempDir(); make(pd, ["gamex86.dll"])
    let pdp = ModLayout.plan(pd, game: gf4)
    check(pdp?.recipe == .mirror && pdp?.copies == [ModCopy(from: pd.appendingPathComponent("gamex86.dll"), to: g4.appendingPathComponent("gamex86.dll"))], "patched dll mirrors onto game file")
    let g5 = tempDir(); make(g5, ["Doom3.exe", "gamex86.dll", "SDL2.dll", "base/", "base/pak000.pk4"])
    let gf5 = GameFolders(exeFolder: g5, root: g5, is64bit: false)
    check(ModLayout.plan(pm, game: gf5)?.recipe == .program, "port sharing SDL2.dll is still a program")
    let colon = tempDir(); make(colon, ["dhe:wm3.exe", "SDL2.dll"])
    check(ModLayout.plan(colon, game: gf5)?.programExe?.deletingLastPathComponent().lastPathComponent == g5.lastPathComponent + " (dhe-wm3)", "program name sanitized")
    check(ModLayout.safeName("a/b:c") == "a-b-c", "safe name")
    let pe2 = tempDir(); make(pe2, ["game.exe", "base/", "base/new.pk4"])
    check(ModLayout.plan(pe2, game: gf4)?.recipe == .mirror, "game's own exe name is mirror, not program")

    let g6 = tempDir(); make(g6, ["Doom3.exe", "base/", "base/pak000.pk4"])
    let gf6 = GameFolders(exeFolder: g6, root: g6, is64bit: false)
    let unpacked = tempDir(); make(unpacked, ["base/", "base/maps/", "base/maps/new.map", "base/textures/", "base/textures/wall.tga"])
    let cr = ModLayout.contentRoot(unpacked, game: gf6)
    check(cr == unpacked, "contentRoot stops at a folder the game has")
    let crp = ModLayout.plan(cr, game: gf6)
    check(crp?.recipe == .mirror && crp?.copies.map(\.to).contains(g6.appendingPathComponent("base/textures/wall.tga")) == true, "base-only archive mirrors")
    let wrapped = tempDir(); make(wrapped, ["My Mod/", "My Mod/BASE/", "My Mod/BASE/maps/new.map"])
    check(ModLayout.contentRoot(wrapped, game: gf6) == wrapped.appendingPathComponent("My Mod"), "wrapper stripped down to the game's folder, ignoring case")

    let ue = tempDir(); make(ue, ["Binaries/", "Binaries/Win64/", "Binaries/Win64/dinput8.dll", "Binaries/Win64/Fix.asi"])
    let ueRoot = ModLayout.contentRoot(ue, game: gf)
    let uep = ModLayout.plan(ueRoot, game: gf)
    check(uep?.recipe == .mirror && uep?.overrides == ["dinput8=n,b"], "proxy dll mirrored into the exe folder gets an override")
    check(uep?.copies.map(\.to).sorted { $0.path < $1.path } == [game.appendingPathComponent("Binaries/Win64/Fix.asi"), game.appendingPathComponent("Binaries/Win64/dinput8.dll")], "files land in Binaries/Win64")
    let noDll = tempDir(); make(noDll, ["base/", "base/maps/", "base/maps/x.map"])
    check(ModLayout.plan(noDll, game: gf)?.recipe == .mirror && ModLayout.plan(noDll, game: gf)?.overrides == [], "mirror with no proxy dll has no overrides")
    let offExe = tempDir(); make(offExe, ["base/", "base/d3d9.dll"])
    check(ModLayout.plan(offExe, game: gf6)?.recipe == .mirror && ModLayout.plan(offExe, game: gf6)?.overrides == [], "proxy dll outside the exe folder gets no override")

    let dup = tempDir(); make(dup, ["a/zzz.pk4", "b/zzz.pk4"])
    check(ModLayout.plan(dup, game: gf) == nil, "colliding data files -> nil")

    let home = FileManager.default.homeDirectoryForCurrentUser
    for risky in [home, home.appendingPathComponent("Downloads"), home.appendingPathComponent("Desktop"), home.appendingPathComponent("Documents"),
                  URL(fileURLWithPath: "/Applications"), URL(fileURLWithPath: "/"), URL(fileURLWithPath: "/Volumes/Games")] {
        check(ModLayout.riskyRootReason(risky) != nil, "risky root \(risky.path)")
    }
    check(ModLayout.riskyRootReason(game) == nil && ModLayout.riskyRootReason(URL(fileURLWithPath: "/Volumes/Games/Doom 3")) == nil, "ordinary game folders are fine")
    let homeGame = GameFolders(exeFolder: home.appendingPathComponent("Downloads"), root: home.appendingPathComponent("Downloads"), is64bit: true)
    check(ModLayout.plan(mm, game: homeGame) == nil && ModLayout.plan(pm, game: homeGame) == nil && ModLayout.plan(dm, game: homeGame) == nil, "risky root refuses mirror, program, data files")
    check(ModLayout.plan(m, game: homeGame)?.recipe == .dropIn, "drop-in still allowed next to the exe")

    check(ModLayout.isModInstaller(inst.appendingPathComponent("ModSetup.exe")) && ModLayout.isModInstaller(inst.appendingPathComponent("Mod.msi")), "exe and msi installers")
    check(!ModLayout.isModInstaller(inst.appendingPathComponent("install.bat")) && !ModLayout.isModInstaller(inst.appendingPathComponent("Setup.msix")), "bat and msix are not mod installers")

    let stored = InstalledMod(name: "Widescreen Fix", source: "GitHub", recipe: .dropIn,
                              files: [ModFileRecord(path: "/g/dinput8.dll", sha256: "ab12", backup: "/b/0-dinput8.dll",
                                                    createdFolders: ["/g/scripts", "/g/scripts/x"]),
                                      ModFileRecord(path: "/g/fix.ini", sha256: "cd34", backup: nil)],
                              overrides: ["dinput8=n,b"], addedGameID: UUID())
    let encoded = try? JSONEncoder().encode([stored])
    let decoded = encoded.flatMap { try? JSONDecoder().decode([InstalledMod].self, from: $0) }
    check(decoded == [stored], "InstalledMod round-trips through JSON")
    let good = String(decoding: try! JSONEncoder().encode(stored), as: UTF8.self)
    let mixed = Data("[\(good), {\"name\": 3}, \(good)]".utf8)
    let lossy = try? JSONDecoder().decode(LossyList<InstalledMod>.self, from: mixed)
    check(lossy?.items == [stored, stored], "bad mod skipped, others kept")

    func zipFile(_ u: URL) {
        try? FileManager.default.createDirectory(at: u.deletingLastPathComponent(), withIntermediateDirectories: true)
        try? (Data("PK\u{3}\u{4}".utf8) + Data(repeating: 0, count: 40)).write(to: u)
    }
    let pg = tempDir(); make(pg, ["DOOM3.exe", "base/", "base/DoomConfig.cfg", "d3xp/"])
    zipFile(pg.appendingPathComponent("base/pak000.pk4")); zipFile(pg.appendingPathComponent("base/pak001.pk4")); zipFile(pg.appendingPathComponent("d3xp/pak000.pk4"))
    let pgf = GameFolders(exeFolder: pg, root: pg, is64bit: false)
    let dl = tempDir(); let pkArchive = dl.appendingPathComponent("z_cstd3_guis.zip"); zipFile(pkArchive)
    let guis = tempDir(); make(guis, ["x.gui", "y.pd"])
    check(ModLayout.plan(guis, game: pgf) == nil, "gui files alone fit no other rule")
    check(ModLayout.packagePlan(archive: pkArchive, modRoot: guis, game: pgf)
          == ModPlan(recipe: .dataFiles, copies: [ModCopy(from: pkArchive, to: pg.appendingPathComponent("base/z_cstd3_guis.pk4"))], overrides: [], programExe: nil),
          "zip mod becomes base/<name>.pk4")
    let withDll = tempDir(); make(withDll, ["guis/x.gui", "bin/hook.dll"])
    check(ModLayout.packagePlan(archive: pkArchive, modRoot: withDll, game: pgf) == nil, "a mod with a .dll is not a package")
    let textPaks = tempDir(); make(textPaks, ["DOOM3.exe", "base/pak000.pk4", "base/pak001.pk4"])
    check(ModLayout.packagePlan(archive: pkArchive, modRoot: guis, game: GameFolders(exeFolder: textPaks, root: textPaks, is64bit: false)) == nil, "game .pk4 files that aren't zips -> nil")
    let notZip = dl.appendingPathComponent("fix.7z"); try? Data("7z not a zip".utf8).write(to: notZip)
    check(ModLayout.packagePlan(archive: notZip, modRoot: guis, game: pgf) == nil, "a mod that isn't a zip -> nil")
    let odd = dl.appendingPathComponent("a:b.zip"); zipFile(odd)
    check(ModLayout.packagePlan(archive: odd, modRoot: guis, game: pgf)?.copies.first?.to == pg.appendingPathComponent("base/a-b.pk4"), "package name made safe")
    let homePkg = GameFolders(exeFolder: home.appendingPathComponent("Downloads"), root: home.appendingPathComponent("Downloads"), is64bit: false)
    check(ModLayout.packagePlan(archive: pkArchive, modRoot: guis, game: homePkg) == nil, "risky root refuses a package")

    check(ModLayout.samePath(URL(fileURLWithPath: "/G/Game/./D3D9.dll"), URL(fileURLWithPath: "/g/game/d3d9.dll")), "same path ignoring case")
    check(!ModLayout.samePath(URL(fileURLWithPath: "/g/game/d3d9.dll"), URL(fileURLWithPath: "/g/game/ddraw.dll")), "different files")
}
